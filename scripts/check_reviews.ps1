<#
.SYNOPSIS
    What waits for the owner's read: one row per document, from its review line, its text and git.
.DESCRIPTION
    The review line sits under the title (the method's review_line.md, the dev guide's
    section Documents): `> written by ... - reviewed by the owner: <date | not yet>`, the dash a middle dot.
    Listed: docs/*.md, the README / CONTRACT / VALIDATION of every part of the table (each row's
    `path` in status.yaml, whatever the stack), and any other tracked .md that carries the line; a
    generated page (`> generated by ...`) is left out.
    The one judge of what waits for his read (the method's contract, the review report): a page read
    is changed only when its text is, the file on disk against the file git holds at the hour of his
    mark (the last commit of the branch's own line, its first parents, at or before it), his review
    line, the `// ` notes, blank lines and trailing spaces left out of both. The hour is his reader's
    record (target/reading.json of the repository read, `docs.<file>.marked`) when it holds an hour
    of his review day, else the end of that day; when git holds no version of the page then, the
    first version it holds after. A page holding an answer of Lorisse's to a note of his with no
    `// ok` under it is `answered`, whatever else its state. A CONTRACT.md that changed says which:
    a clause (`- **C-n.m**`) added, removed or reworded, or the wording only.
    A report, never a failure: exit 0 always. Called by method/gate/verify.ps1 with -Summary.
    Paths from git: `-c core.quotepath=off` and git's output read as UTF-8, so a non-ASCII name comes
    back as itself; a quoted one is read back all the same. Its report is written in UTF-8 when a
    program reads it (output redirected).
    The owner's mark: a word may follow his date after a comma, `, ok` or `, to rework` (no word:
    read). Every row ends on the mark, three spaces after the verdict: read | ok | to rework (`-` for
    a document never reviewed, with no line, or with a word after the comma that is no mark: the
    summary counts those rows as `unknown mark`). Under the row of a contract whose text changed, one
    line more, indented, holding a colon: `    clauses: C-4.1 reworded, C-4.9 added` or
    `    clauses: none changed, the wording only`. The summary counts an answered page by the state of
    its text. -Marks is kept for its callers and changes nothing.
    -Json prints, in place of the rows, one JSON object: `summary` (the summary line) and `files`, one
    entry a file: file, state (the row's word), text (the state its text alone gives), answered, date,
    mark, unknown_mark, since (hour, day or null), hour (the moment compared with), base (the commit
    compared with), change (the day of the last change, when changed), clauses ({added, removed,
    reworded} for a contract that changed, else null), wording_only. Nothing is written; nothing of the
    repository read is run.
    -Root reads another repository (the project page's way of pointing it at the one it reads).
.EXAMPLE
    .\scripts\check_reviews.ps1 -Summary
.EXAMPLE
    .\scripts\check_reviews.ps1 -Root C:\software\other -Json
#>
[CmdletBinding()]
param([switch] $Summary, [switch] $Marks, [switch] $Json, [string] $Root = '')

# The repository read: -Root, else the one holding this script (a project's scripts/ or the method's method/checks/).
if ($Root) {
    $root = (Resolve-Path -LiteralPath $Root).Path
    $top = & git -C $root rev-parse --show-toplevel 2>$null
} else {
    $root = Split-Path -Parent $PSScriptRoot
    $top = & git -C $PSScriptRoot rev-parse --show-toplevel 2>$null
}
if ($LASTEXITCODE -eq 0 -and $top) { $root = ([string] $top).Replace('/', '\') }
$reviewLine = '^>\s.*reviewed by the owner:\s*(\d{4}-\d{2}-\d{2}|not yet)'
$utf8 = New-Object System.Text.UTF8Encoding($false)
$inv = [Globalization.CultureInfo]::InvariantCulture
# The console's encoding before this script: put back at the end (a terminal keeps its own).
$consoleWas = $null
try { $consoleWas = [Console]::OutputEncoding } catch { $consoleWas = $null }
if ($consoleWas -and [Console]::IsOutputRedirected) { try { [Console]::OutputEncoding = $utf8 } catch { } }

# Git, its output read as UTF-8, paths never quoted.
function Invoke-Git([string[]] $a) {
    $prev = $null
    try { $prev = [Console]::OutputEncoding; [Console]::OutputEncoding = $utf8 } catch { $prev = $null }
    try { return @(& git -C $root -c core.quotepath=off @a 2>$null) } finally { if ($prev) { try { [Console]::OutputEncoding = $prev } catch { } } }
}

# A path as git may print it: a C-quoted one (`"a \302\265.md"`, octal bytes of UTF-8) read back to its name.
function ConvertFrom-GitPath([string] $v) {
    $v = "$v".Trim()
    if (-not ($v.Length -ge 2 -and $v[0] -eq '"' -and $v[$v.Length - 1] -eq '"')) { return $v }
    $s = $v.Substring(1, $v.Length - 2)
    $bytes = New-Object System.Collections.Generic.List[byte]
    $esc = @{ 'n' = 10; 't' = 9; 'r' = 13; 'a' = 7; 'b' = 8; 'f' = 12; 'v' = 11; '"' = 34; '\' = 92 }
    $i = 0
    while ($i -lt $s.Length) {
        $c = $s[$i]
        if ($c -eq '\' -and $s.Substring($i + 1) -match '^([0-7]{3})') { $bytes.Add([byte] [Convert]::ToInt32($Matches[1], 8)); $i += 4; continue }
        if ($c -eq '\' -and $i + 1 -lt $s.Length -and $esc.ContainsKey([string] $s[$i + 1])) { $bytes.Add([byte] $esc[[string] $s[$i + 1]]); $i += 2; continue }
        foreach ($b in $utf8.GetBytes([string] $c)) { $bytes.Add($b) }
        $i++
    }
    return $utf8.GetString($bytes.ToArray())
}

# The first lines of a file, where its review line sits: eight lines, counted after a front matter
# (a block between two `---` lines at the top, as a command file carries) when the file has one.
function Get-Head([string] $rel) {
    $lines = @(Get-Content -LiteralPath (Join-Path $root $rel) -TotalCount 40 -Encoding UTF8)
    $start = 0
    if ($lines.Count -gt 0 -and $lines[0] -eq '---') {
        for ($i = 1; $i -lt $lines.Count; $i++) { if ($lines[$i] -eq '---') { $start = $i + 1; break } }
    }
    $end = [Math]::Min($lines.Count, $start + 8)
    if ($end -le $start) { return @() }
    return $lines[$start..($end - 1)]
}

# The parts of the table: each row's `path` (status.yaml at the root, one row per line, as the edit
# hook reads it); a "-" path or no table gives none.
function Get-PartPaths {
    $table = Join-Path $root 'status.yaml'
    if (-not (Test-Path -LiteralPath $table)) { return @() }
    $paths = foreach ($line in Get-Content -LiteralPath $table -Encoding UTF8) {
        if ($line -notmatch '^\s*[A-Za-z0-9_.-]+:\s*\{(.*)\}\s*$') { continue }
        if ($Matches[1] -notmatch 'path:\s*([^,}\s]+)') { continue }
        $p = $Matches[1].Trim('"', "'").Replace('\', '/').TrimEnd('/')
        if ($p -and $p -ne '-') { $p }
    }
    @($paths | Select-Object -Unique)
}

# The documents under the rule, as paths relative to the repo root.
function Get-ReviewedFiles {
    $listed = @()
    $docs = Join-Path $root 'docs'
    if (Test-Path -LiteralPath $docs) { $listed += @(Get-ChildItem -LiteralPath $docs -File -Filter '*.md' | ForEach-Object { 'docs/' + $_.Name }) }
    foreach ($part in Get-PartPaths) {
        foreach ($name in 'README.md', 'CONTRACT.md', 'VALIDATION.md') {
            $rel = if ($part -eq '.') { $name } else { "$part/$name" }
            if (Test-Path -LiteralPath (Join-Path $root $rel) -PathType Leaf) { $listed += $rel }
        }
    }
    $listed = @($listed | Select-Object -Unique)
    $tracked = @(Invoke-Git @('ls-files', '--', '*.md') | ForEach-Object { ConvertFrom-GitPath $_ } | Where-Object { $_ -and $listed -notcontains $_ })
    $carrying = $tracked | Where-Object { (Test-Path -LiteralPath (Join-Path $root $_) -PathType Leaf) -and (@(Get-Head $_) -match $reviewLine) }
    @($listed) + @($carrying) | Where-Object { -not (@(Get-Head $_) -match '^>\s*generated by') } | Sort-Object
}

# The review field of a file's line: a date, 'not yet', or $null when the file has no line.
function Get-ReviewField([string] $rel) {
    foreach ($line in Get-Head $rel) {
        if ($line -match $reviewLine) { return $Matches[1] }
    }
    return $null
}

# The owner's mark after his date: read (no word), ok, to rework; '-' with no date. A word after the
# comma that is no mark: '-', and the row counted as an unknown mark.
function Get-ReviewMark([string] $rel) {
    foreach ($line in Get-Head $rel) {
        if ($line -match '^>\s.*reviewed by the owner:\s*(\d{4}-\d{2}-\d{2}|not yet)(.*)$') {
            if ($Matches[1] -eq 'not yet') { return [pscustomobject]@{ mark = '-'; unknown = $false } }
            $rest = $Matches[2].Trim()
            if (-not $rest.StartsWith(',')) { return [pscustomobject]@{ mark = 'read'; unknown = $false } }
            $word = $rest.Substring(1).Trim()
            if ($word -ceq 'ok' -or $word -ceq 'to rework') { return [pscustomobject]@{ mark = $word; unknown = $false } }
            return [pscustomobject]@{ mark = '-'; unknown = $true }
        }
    }
    return [pscustomobject]@{ mark = '-'; unknown = $false }
}

# -- the hour of his mark and the text he marked -------------------------------------------------------------
# His reader's record: `docs.<file>.marked`, an hour with its offset (a string, or a date when a reader made one).
$markedAt = @{}
$recordPath = Join-Path $root 'target\reading.json'
if (Test-Path -LiteralPath $recordPath -PathType Leaf) {
    $record = $null
    try { $record = [IO.File]::ReadAllText($recordPath, $utf8) | ConvertFrom-Json } catch { $record = $null }
    if ($record -and $record.docs) {
        foreach ($pr in $record.docs.PSObject.Properties) {
            $mv = $pr.Value.marked
            if ($mv -is [datetime]) { $mv = $mv.ToString('yyyy-MM-ddTHH:mm:sszzz', $inv) }
            if ($mv) { $markedAt[($pr.Name -replace '\\', '/')] = [string] $mv }
        }
    }
}

# The branch's own line (its first parents) with its commit times, read once: the last commit at or before a moment.
$script:lineCommits = $null
$baseAt = @{}
function Get-BaseCommit([string] $before) {
    if (-not $baseAt.ContainsKey($before)) {
        if ($null -eq $script:lineCommits) {
            $script:lineCommits = @(Invoke-Git @('log', '--first-parent', '--format=%H %ct', 'HEAD') | ForEach-Object { $p = "$_" -split ' '; if ($p.Count -eq 2) { , @($p[0], [int64] $p[1]) } })
        }
        $limit = $null
        try { $limit = ([DateTimeOffset]::Parse($before, $inv)).ToUnixTimeSeconds() } catch { $limit = $null }
        $hit = ''
        if ($null -ne $limit) { foreach ($c in $script:lineCommits) { if ($c[1] -le $limit) { $hit = [string] $c[0]; break } } }
        $baseAt[$before] = $hit
    }
    return $baseAt[$before]
}

# Files as they stood at commits, `<commit>:<path>` each, fetched in one git call (cat-file --batch) and kept: the
# lines of each, $null for one git does not have.
$blobs = @{}
function Get-Blobs([string[]] $specs) {
    $want = @($specs | Where-Object { $_ -and -not $blobs.ContainsKey($_) } | Select-Object -Unique)
    if (-not $want.Count) { return }
    $OutputEncoding = $utf8
    $prev = $null
    try { $prev = [Console]::OutputEncoding; [Console]::OutputEncoding = $utf8 } catch { $prev = $null }
    # a first line of no object: Windows PowerShell may put a byte order mark before what it pipes, which spoils the
    # first name sent (git then says it is missing)
    try { $out = @(@('-') + $want | & git -C $root -c core.quotepath=off cat-file --batch 2>$null) } finally { if ($prev) { try { [Console]::OutputEncoding = $prev } catch { } } }
    $k = -1; $cur = $null
    $flush = { if ($k -ge 0 -and $null -ne $cur) { if ($cur.Count -and $cur[$cur.Count - 1] -eq '') { $cur.RemoveAt($cur.Count - 1) }; $blobs[$want[$k]] = $cur.ToArray() } }
    foreach ($l in $out) {
        if ($k + 1 -lt $want.Count -and ("$l" -match '^[0-9a-f]{40,64} blob \d+$' -or "$l" -ceq ($want[$k + 1] + ' missing'))) {
            . $flush
            $k++
            if ("$l" -match ' missing$') { $blobs[$want[$k]] = $null; $cur = $null } else { $cur = New-Object System.Collections.Generic.List[string] }
            continue
        }
        if ($null -ne $cur) { $cur.Add("$l") }
    }
    . $flush
    foreach ($w in $want) { if (-not $blobs.ContainsKey($w)) { $blobs[$w] = $null } }
}

# The moment a read page is compared with: {before, since}; the record's hour when it is of his review day.
function Get-Moment([string] $rel, [string] $date) {
    if ($markedAt.ContainsKey($rel) -and $markedAt[$rel].StartsWith($date)) { return [pscustomobject]@{ before = $markedAt[$rel]; since = 'hour' } }
    return [pscustomobject]@{ before = ('{0} 23:59:59' -f $date); since = 'day' }
}

# A page's text as compared: its review line, the `// ` lines, blank lines and trailing spaces left out.
function Get-Body([string] $text) {
    $keep = New-Object System.Collections.Generic.List[string]
    foreach ($l in ($text.TrimStart([char] 0xFEFF) -split "`r?`n")) {
        $t = $l.TrimEnd()
        if (-not $t.Trim()) { continue }
        if ($t -match '^>\s.*reviewed by the owner:') { continue }
        if ($t.TrimStart().StartsWith('//')) { continue }
        $keep.Add($t)
    }
    return ($keep -join "`n")
}

# A contract's clauses: each `- **C-n.m**` line, its trailing spaces left out, by its number.
function Get-Clauses([string[]] $lines) {
    $m = [ordered]@{}
    foreach ($l in $lines) {
        if ("$l" -match '^\s*- \*\*(C-\d+\.\d+)\*\*') {
            $id = $Matches[1]
            if ($m.Contains($id)) { $m[$id] = $m[$id] + "`n" + "$l".TrimEnd() } else { $m[$id] = "$l".TrimEnd() }
        }
    }
    return $m
}

# A thread where a note of his has a `// Lorisse: ` answer under it and no `// ok` under the answer; a line inside a
# code fence is no note.
function Test-OpenAnswer([string] $text) {
    $fence = $false; $group = New-Object System.Collections.Generic.List[string]
    foreach ($l in (@($text -split "`r?`n") + '')) {
        if ($l -match '^\s*(```|~~~)') { $fence = -not $fence }
        $t = $l.Trim()
        if (-not $fence -and $t.StartsWith('//')) { $group.Add($t); continue }
        if ($group.Count) {
            $ans = -1
            for ($i = 0; $i -lt $group.Count; $i++) { if ($group[$i] -match '^//\s*Lorisse:') { $ans = $i } }
            if ($ans -gt 0) {
                $mine = @($group | Select-Object -First $ans | Where-Object { $_ -notmatch '^//\s*(Lorisse:|ok\b)' }).Count
                $ok = @($group | Select-Object -Skip ($ans + 1) | Where-Object { $_ -match '(?i)^//\s*ok\b' }).Count
                if ($mine -and -not $ok) { return $true }
            }
            $group.Clear()
        }
    }
    return $false
}

# -- the verdicts --------------------------------------------------------------------------------------------
$files = @(Get-ReviewedFiles)
$entries = @()
foreach ($rel in $files) {
    $field = Get-ReviewField $rel
    $mark = Get-ReviewMark $rel
    $e = [ordered]@{ file = $rel; state = ''; text = ''; answered = $false; date = $null; mark = $mark.mark; unknown_mark = [bool] $mark.unknown
        since = $null; hour = $null; base = $null; change = $null; clauses = $null; wording_only = $false }
    if (-not $field) { $e.text = 'no line' }
    elseif ($field -eq 'not yet') { $e.text = 'never reviewed' }
    else {
        $e.date = $field
        $mo = Get-Moment $rel $field
        $e.since = $mo.since; $e.hour = $mo.before
        $e.base = Get-BaseCommit $mo.before
        $e.text = 'reviewed'
    }
    $entries += $e
}
# every marked version fetched in one git call; a page git did not hold then: its first version after
Get-Blobs @($entries | Where-Object { $_.base } | ForEach-Object { '{0}:{1}' -f $_.base, $_.file })
foreach ($e in @($entries | Where-Object { $_.date })) {
    if ($e.base -and $null -ne $blobs[('{0}:{1}' -f $e.base, $e.file)]) { continue }
    $first = @(Invoke-Git @('log', '--first-parent', '--format=%H', 'HEAD', '--', $e.file)) | Select-Object -Last 1
    $e.base = $null
    if ($first) { $e.base = [string] $first; Get-Blobs @(('{0}:{1}' -f $e.base, $e.file)) }
}
$script:dirty = $null
foreach ($e in $entries) {
    $full = Join-Path $root $e.file
    $now = $null
    try { $now = [IO.File]::ReadAllText($full, $utf8) } catch { $now = $null }
    if ($null -ne $now) { $e.answered = [bool] (Test-OpenAnswer $now) }
    if (-not $e.date -or -not $e.base -or $null -eq $now) { continue }
    $old = $blobs[('{0}:{1}' -f $e.base, $e.file)]
    if ($null -eq $old) { $e.base = $null; continue }
    if ((Get-Body (@($old) -join "`n")) -ceq (Get-Body $now)) { continue }
    $e.text = 'changed since'
    if ($null -eq $script:dirty) {
        $script:dirty = @{}
        foreach ($l in (Invoke-Git @('status', '--porcelain', '--untracked-files=no'))) { if ("$l".Length -gt 3) { $script:dirty[(ConvertFrom-GitPath "$l".Substring(3))] = $true } }
    }
    $chg = ''
    if ($script:dirty.ContainsKey($e.file)) { $chg = (Get-Item -LiteralPath $full).LastWriteTime.ToString('yyyy-MM-dd', $inv) }
    else { $chg = [string] (Invoke-Git @('log', '-1', '--format=%cs', '--', $e.file) | Select-Object -First 1) }
    if (-not $chg) { $chg = $e.date }
    $e.change = $chg
    if ((Split-Path -Leaf $e.file) -ceq 'CONTRACT.md') {
        $was = Get-Clauses @($old)
        $is = Get-Clauses @($now -split "`r?`n")
        $c = [ordered]@{ added = @(); removed = @(); reworded = @() }
        foreach ($id in $is.Keys) { if (-not $was.Contains($id)) { $c.added += $id } elseif ($was[$id] -cne $is[$id]) { $c.reworded += $id } }
        foreach ($id in $was.Keys) { if (-not $is.Contains($id)) { $c.removed += $id } }
        $e.clauses = $c
        $e.wording_only = -not ($c.added.Count + $c.removed.Count + $c.reworded.Count)
    }
}
foreach ($e in $entries) {
    $e.state = $e.text
    if ($e.answered) { $e.state = 'answered' }
}

# -- what is printed -----------------------------------------------------------------------------------------
$kinds = 'reviewed', 'changed since', 'never reviewed', 'no line'
$counts = foreach ($k in $kinds) { '{0} {1}' -f @($entries | Where-Object { $_.text -eq $k }).Count, $k }
$counts = @($counts) + ('{0} unknown mark' -f @($entries | Where-Object { $_.unknown_mark }).Count)
$summaryLine = 'reviews: {0} file(s): {1}' -f @($entries).Count, ($counts -join ', ')

if ($Json) {
    $obj = [ordered]@{ summary = $summaryLine; files = @($entries) }
    [Console]::Out.WriteLine((ConvertTo-Json -InputObject $obj -Depth 6 -Compress))
} else {
    if (-not $Summary) {
        foreach ($e in $entries) {
            $verdict = $e.state
            if ($e.state -eq 'reviewed') { $verdict = 'reviewed {0}' -f $e.date }
            elseif ($e.state -eq 'changed since') { $verdict = 'changed since {0} (last change {1})' -f $e.date, $e.change }
            Write-Host ('{0,-50} {1}   {2}' -f $e.file, $verdict, $e.mark)
            if ($e.clauses) {
                $said = @()
                foreach ($w in 'added', 'removed', 'reworded') { foreach ($id in $e.clauses[$w]) { $said += ('{0} {1}' -f $id, $w) } }
                if ($said.Count) { Write-Host ('    clauses: {0}' -f ($said -join ', ')) } else { Write-Host '    clauses: none changed, the wording only' }
            }
        }
        Write-Host ''
    }
    Write-Host $summaryLine
}
if ($consoleWas -and [Console]::IsOutputRedirected) { try { [Console]::OutputEncoding = $consoleWas } catch { } }
exit 0
